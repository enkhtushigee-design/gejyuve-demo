import type { Quiz, QuizQuestion, QuizLevel, Subject } from "../types";

type RawQ = Omit<QuizQuestion, "id">;

function q(text: string, options: string[], correctIndex: number, explanation: string): RawQ {
  return { text, options, correctIndex, explanation };
}

function buildQuiz(
  clubId: string,
  subject: Subject,
  level: QuizLevel,
  title: string,
  levelLabel: string,
  description: string,
  xpPerQuestion: number,
  raw: RawQ[]
): Quiz {
  return {
    id: `${clubId}-l${level}`,
    clubId,
    subject,
    level,
    title,
    levelLabel,
    description,
    xpPerQuestion,
    questions: raw.map((r, i) => ({ id: `${clubId}-l${level}-q${i + 1}`, ...r })),
  };
}

